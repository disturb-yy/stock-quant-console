import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const source = process.argv[2] || process.env.OPENAPI_SOURCE
const output = resolve(process.argv[3] || 'src/api/generated.ts')

if (!source) {
  throw new Error('请提供 OpenAPI URL 或 JSON 文件路径，例如 npm run sync:api-types -- http://127.0.0.1:8357/api/v1/openapi.json')
}

function typeName(reference) {
  const raw = reference.split('/').pop() || 'AnonymousSchema'
  const normalized = raw.replace(/[^a-zA-Z0-9_$]/g, '_')
  return /^[0-9]/.test(normalized) ? `Schema_${normalized}` : normalized
}

function literal(value) {
  return JSON.stringify(value)
}

function schemaType(schema) {
  if (!schema || typeof schema !== 'object') return 'unknown'
  if (schema.$ref) return typeName(schema.$ref)
  if (schema.oneOf) return schema.oneOf.map(schemaType).join(' | ')
  if (schema.anyOf) return schema.anyOf.map(schemaType).join(' | ')
  if (schema.allOf) return schema.allOf.map(schemaType).join(' & ')
  if (schema.enum) return schema.enum.map(literal).join(' | ')
  if (schema.type === 'array') return `ReadonlyArray<${schemaType(schema.items)}>`
  if (schema.type === 'object' || schema.properties) return objectType(schema)
  if (schema.type === 'string') return 'string'
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  return 'unknown'
}

function objectType(schema) {
  const required = new Set(schema.required || [])
  const properties = Object.entries(schema.properties || {})
  const fields = properties.map(([name, value]) => {
    const optional = required.has(name) ? '' : '?'
    return `readonly ${literal(name)}${optional}: ${schemaType(value)}`
  })
  if (schema.additionalProperties === true) {
    fields.push('readonly [key: string]: unknown')
  } else if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
    fields.push(`readonly [key: string]: ${schemaType(schema.additionalProperties)}`)
  }
  return fields.length ? `{ ${fields.join('; ')} }` : 'Record<string, never>'
}

function contentType(content) {
  const fields = Object.entries(content || {}).map(([mediaType, media]) => {
    return `readonly ${literal(mediaType)}: ${schemaType(media.schema)}`
  })
  return fields.length ? `{ ${fields.join('; ')} }` : 'Record<string, never>'
}

function operationType(operation) {
  const responses = Object.entries(operation.responses || {}).map(([status, response]) => {
    const content = response.content ? `; readonly content: ${contentType(response.content)}` : ''
    return `readonly ${literal(status)}: {${content.slice(1)}}`
  })
  const requestBody = operation.requestBody?.content
    ? `; readonly requestBody: { readonly content: ${contentType(operation.requestBody.content)} }`
    : ''
  return `{ readonly responses: { ${responses.join('; ')} }${requestBody} }`
}

function pathsType(paths) {
  const pathEntries = Object.entries(paths || {}).map(([path, pathItem]) => {
    const operations = Object.entries(pathItem)
      .filter(([method]) => ['get', 'post', 'put', 'patch', 'delete', 'options', 'head'].includes(method))
      .map(([method, operation]) => `readonly ${method}: ${operationType(operation)}`)
    return `readonly ${literal(path)}: { ${operations.join('; ')} }`
  })
  return pathEntries.length ? `{ ${pathEntries.join('; ')} }` : 'Record<string, never>'
}

function render(document) {
  const schemas = Object.entries(document.components?.schemas || {})
    .map(([name, schema]) => `export type ${typeName(name)} = ${schemaType(schema)}\n`)
    .join('\n')
  return [
    '// Generated by scripts/sync-openapi-types.mjs. Do not edit by hand.',
    `// OpenAPI version: ${document.openapi || 'unknown'}`,
    '',
    schemas,
    `export type ApiPaths = ${pathsType(document.paths)}\n`,
  ].join('\n')
}

async function loadDocument(input) {
  const raw = /^https?:\/\//.test(input)
    ? await (async () => {
        const response = await fetch(input, { headers: { Accept: 'application/json' } })
        if (!response.ok) throw new Error(`读取 OpenAPI 失败: HTTP ${response.status}`)
        return response.text()
      })()
    : await readFile(resolve(input), 'utf8')
  try {
    return JSON.parse(raw)
  } catch (cause) {
    throw new Error('OpenAPI 不是有效 JSON', { cause })
  }
}

const document = await loadDocument(source)
if (!document.openapi || typeof document.paths !== 'object') {
  throw new Error('OpenAPI 缺少 openapi 或 paths 字段')
}
await mkdir(dirname(output), { recursive: true })
await writeFile(output, render(document), 'utf8')
console.log(`已从 ${source} 同步 OpenAPI 类型到 ${output}`)
